// 시험판 56: 말로 · 글로 넣기에서 '부터' 없이 적은 끝 시각(대표 위젯 사진 11/5 13:44 '12시까지 경영학 수업')
// '10시 12시까지' · '10시에서 12시까지' · '3시 4시 반까지'는 시작 ~ 끝으로, 이름에 '12시까지'가 남지 않는다.
// 시각 하나에 '까지'만 붙은 말('12시까지 보고서 제출')과, 시각 사이에 다른 말이 낀 것('9시 회의 10시까지 …')은 전처럼
const { openApp, checker } = require('./harness.cjs');

module.exports = async function () {
  const c = checker('시험판 56 · 부터 없이 적은 끝 시각');
  const app = await openApp({});
  const p = app.page;
  try {
    const parse = t => p.evaluate(x => { const r = window.BX_parse(x); return [r.title, r.start, r.end || null]; }, t);
    c.eq(await parse('10시 12시까지 경영학 수업'), ['경영학 수업', '10:00', '12:00'], "'10시 12시까지' → 오전 10:00 ~ 오후 12:00, 이름은 '경영학 수업'");
    c.eq(await parse('10시에서 12시까지 경영학'), ['경영학', '10:00', '12:00'], "'10시에서 12시까지'도 범위");
    c.eq(await parse('오후 2시 3시까지 회의'), ['회의', '14:00', '15:00'], '오전 · 오후는 앞 시각을 따름');
    c.eq(await parse('3시 4시 반까지 회의'), ['회의', '15:00', '16:30'], "'4시 반까지'도 끝 시각");
    c.eq(await parse('내일 9시 반 11시까지 병원'), ['병원', '09:30', '11:00'], "'9시 반 11시까지'");
    c.eq(await parse('11시 1시까지 점심'), ['점심', '11:00', '13:00'], '끝이 앞보다 작으면 오후로');
    c.eq(await parse('내일 10시부터 12시까지 경영학 수업'), ['경영학 수업', '10:00', '12:00'], "'부터'가 있는 말은 전처럼");
    c.eq(await parse('12시까지 보고서 제출'), ['보고서 제출', '12:00', null], "시각 하나 + '까지'는 전처럼(시작 시각)");
    c.eq(await parse('9시 회의 10시까지 자료 정리'), ['회의 10시까지 자료 정리', '09:00', null], '시각 사이에 다른 말이 끼면 전처럼');
    c.eq(app.errors, [], '화면 오류');
  } finally { await app.close(); }
  return c.done();
};
